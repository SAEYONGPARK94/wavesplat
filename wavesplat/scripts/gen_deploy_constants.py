#!/usr/bin/env python3
"""배포 상수 -> `thesis/deploy_constants.tex` 생성.

★저장소가 *"같은 값을 여러 곳에 적어 어긋남"* 에 **여섯 번** 물렸고 2026-08-19 에
스스로 처방했다: **"개입 기대값은 단일출처여야 한다."**
2026-08-22 에 그 결함이 **논문에서** 재발했다 — 오전에 쓴 라우터 서술이 오후 배포로
낡았는데 저녁 편집이 못 잡았다(8시간 46분). 이 스크립트가 그 처방을 논문에 적용한다.

⟹ **논문은 배포 상수를 문자로 다시 적지 않는다.** `\\input{deploy_constants}` 만 한다.
`wavesplat/tests/test_shipping_defaults.py::test_thesis_deploy_constants_are_current`
가 이 파일이 현 배포값과 일치하는지 검사한다.
"""
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, ROOT)
OUT = os.path.join(ROOT, 'thesis', 'deploy_constants.tex')


def render() -> str:
    from wavesplat.run import DEFAULT_CONFIG
    from wavesplat.optimizer.sequential_update import (
        AUTO_SWITCH_THRESH_PRE_UNIFY, LEARNED_INIT_ITERS_PRE_VARPRO)
    n_tests = _count_tests()
    c = DEFAULT_CONFIG
    rows = [
        ('DeployLambdaOne', f"10^{{{_exp(c['lambda_l1'])}}}"),
        ('DeployLambdaSmooth', f"10^{{{_exp(c['lambda_smooth'])}}}"),
        ('DeployVarproSteps', str(c['varpro_steps'])),
        ('DeployLearnedInitIters', str(c['learned_init_iters'])),
        ('DeployRouterThresh', str(c['auto_switch_thresh'])),
        ('DeployInitMethod', str(c['init_method'])),
        ('DeployTrackingMode', str(c['tracking_mode'])),
        ('DeployEnsembleK', str(c['analytic_ensemble_k'])),
        # 2026-08-23: 실측 전용 경로. 배포했다가 같은 날 철회 ⟹ 값은 'frozen'.
        ('DeployBankRefit', 'frozen' if c['bank_refit_every_s'] is None
         else f"{c['bank_refit_every_s']:g}\\,s"),
        ('DeployBankRefitAsync', 'off' if not c.get('bank_refit_async') else 'on'),
        ('DeployNumTests', str(n_tests)),
        ('PreUnifyRouterThresh', str(AUTO_SWITCH_THRESH_PRE_UNIFY)),
        ('PreVarproInitIters', str(LEARNED_INIT_ITERS_PRE_VARPRO)),
    ]
    body = '\n'.join(f'\\newcommand{{\\{k}}}{{{v}}}' for k, v in rows)
    return ('% AUTO-GENERATED by scripts/gen_deploy_constants.py -- DO NOT EDIT BY HAND.\n'
            '% 논문은 배포 상수를 문자로 적지 않는다. 이 파일을 \\input 하고 매크로만 쓴다.\n'
            '% 근거: 2026-08-22 에 논문의 라우터 서술이 같은 날 배포로 8시간 46분 만에\n'
            '%       낡았다(심사 R3-1 §1.6). 저장소 처방 "개입 기대값은 단일출처" 의 논문 적용.\n'
            + body + '\n')


def _exp(x):
    import math
    return int(round(math.log10(float(x))))


def _count_tests() -> int:
    try:
        r = subprocess.run([sys.executable, '-m', 'pytest', '--collect-only', '-q',
                            'wavesim/tests/', 'wavesplat/tests/'],
                           cwd=ROOT, capture_output=True, text=True, timeout=300)
        for line in r.stdout.strip().splitlines()[::-1]:
            if 'test' in line and '/' not in line:
                tok = line.split()[0]
                if tok.isdigit():
                    return int(tok)
    except Exception:
        pass
    return -1


if __name__ == '__main__':
    txt = render()
    with open(OUT, 'w') as f:
        f.write(txt)
    print(txt)
    print(f'\n기록: {OUT}')
