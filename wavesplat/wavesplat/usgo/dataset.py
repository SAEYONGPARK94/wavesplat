"""
USGO Dataset: load training data from npz generated by generate_usgo_data.py.

Each sample provides:
  - Sparse observations (x, y, z, conf) with variable count (padded)
  - GT spectral params (kx, ky, w, phi) with variable N_comp (padded)
  - Beamforming init params (kx, ky, w, phi) with fixed N_init
  - Metadata: t, depth, Hs, n_obs, n_comp
"""

import numpy as np
import torch
from torch.utils.data import Dataset


class USGODataset(Dataset):
    """Dataset for USGO training from npz file."""

    def __init__(self, npz_path: str, device: str = 'cpu'):
        data = np.load(npz_path)

        self.obs_x = torch.tensor(data['obs_x'], dtype=torch.float32)
        self.obs_y = torch.tensor(data['obs_y'], dtype=torch.float32)
        self.obs_z = torch.tensor(data['obs_z'], dtype=torch.float32)
        self.obs_conf = torch.tensor(data['obs_conf'], dtype=torch.float32)
        self.n_obs = torch.tensor(data['n_obs'], dtype=torch.int32)

        self.gt_kx = torch.tensor(data['gt_kx'], dtype=torch.float32)
        self.gt_ky = torch.tensor(data['gt_ky'], dtype=torch.float32)
        self.gt_w = torch.tensor(data['gt_w'], dtype=torch.float32)
        self.gt_phi = torch.tensor(data['gt_phi'], dtype=torch.float32)
        self.gt_omega = torch.tensor(data['gt_omega'], dtype=torch.float32)
        self.n_comp = torch.tensor(data['n_comp'], dtype=torch.int32)

        self.init_kx = torch.tensor(data['init_kx'], dtype=torch.float32)
        self.init_ky = torch.tensor(data['init_ky'], dtype=torch.float32)
        self.init_w = torch.tensor(data['init_w'], dtype=torch.float32)
        self.init_phi = torch.tensor(data['init_phi'], dtype=torch.float32)

        self.t = torch.tensor(data['t'], dtype=torch.float32)
        self.depth = torch.tensor(data['depth'], dtype=torch.float32)
        self.Hs = torch.tensor(data['Hs'], dtype=torch.float32)

        self.n_init = int(data['n_init'])
        self.max_obs = int(data['max_obs'])
        self.max_comp = int(data['max_comp'])

        self.device = device

    def __len__(self):
        return len(self.t)

    def __getitem__(self, idx):
        n = int(self.n_obs[idx])
        nc = int(self.n_comp[idx])

        return {
            # Observations (only valid entries)
            'obs_x': self.obs_x[idx, :n],
            'obs_y': self.obs_y[idx, :n],
            'obs_z': self.obs_z[idx, :n],
            'obs_conf': self.obs_conf[idx, :n],
            'n_obs': n,
            # GT (only valid components)
            'gt_kx': self.gt_kx[idx, :nc],
            'gt_ky': self.gt_ky[idx, :nc],
            'gt_w': self.gt_w[idx, :nc],
            'gt_phi': self.gt_phi[idx, :nc],
            'gt_omega': self.gt_omega[idx, :nc],
            'n_comp': nc,
            # Init (fixed size)
            'init_kx': self.init_kx[idx],
            'init_ky': self.init_ky[idx],
            'init_w': self.init_w[idx],
            'init_phi': self.init_phi[idx],
            # Metadata
            't': self.t[idx],
            'depth': self.depth[idx],
            'Hs': self.Hs[idx],
        }


def generate_gt_field(gt_kx, gt_ky, gt_w, gt_phi, gt_omega,
                      grid_x, grid_y, t):
    """Generate GT wave field on a regular grid from spectral params.

    Args:
        gt_kx, gt_ky, gt_w, gt_phi, gt_omega: (N_comp,) GT spectral params
        grid_x: (Gx,) x grid coordinates
        grid_y: (Gy,) y grid coordinates
        t: scalar time

    Returns:
        Z_gt: (Gy, Gx) GT wave elevation
    """
    Xg, Yg = torch.meshgrid(grid_x, grid_y, indexing='xy')
    x_flat = Xg.reshape(-1)  # (Gx*Gy,)
    y_flat = Yg.reshape(-1)

    # phase: (M, N)
    phase = (gt_kx[None, :] * x_flat[:, None]
             + gt_ky[None, :] * y_flat[:, None]
             - gt_omega[None, :] * t
             + gt_phi[None, :])

    z = torch.sum(gt_w[None, :] * torch.cos(phase), dim=1)
    return z.reshape(len(grid_y), len(grid_x))
